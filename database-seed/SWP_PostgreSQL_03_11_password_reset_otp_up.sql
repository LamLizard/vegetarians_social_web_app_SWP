-- SWP391 · Green Bowl — Quên mật khẩu (OTP qua email)
-- Ngày: 03/11
-- Mục đích: bảng lưu mã OTP đặt lại mật khẩu + vé (reset token) cấp sau khi
--           xác minh OTP thành công. Tách khỏi registration_otp để luồng đăng ký
--           và luồng quên mật khẩu không ghi đè dữ liệu của nhau
--           (cùng một email có thể vừa đăng ký dở vừa yêu cầu đặt lại mật khẩu).
-- Chạy: 1 lần trên DB đang dùng (Neon/Render). Script idempotent — chạy lại an toàn.
-- =============================================================================

CREATE TABLE IF NOT EXISTS password_reset_otp (
    password_reset_otp_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                 VARCHAR(255) NOT NULL UNIQUE,
    otp_hash              VARCHAR(255) NOT NULL,
    reset_token_hash      VARCHAR(255),
    expires_at            TIMESTAMPTZ  NOT NULL,
    reset_token_expires_at TIMESTAMPTZ,
    attempts              INT          NOT NULL DEFAULT 0,
    last_sent_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Vé reset chỉ dùng 1 lần và tra theo hash → cần index.
CREATE INDEX IF NOT EXISTS idx_password_reset_otp_token
    ON password_reset_otp (reset_token_hash);

COMMENT ON TABLE  password_reset_otp IS 'OTP + reset token cho luồng Quên mật khẩu';
COMMENT ON COLUMN password_reset_otp.otp_hash IS 'bcrypt hash của mã OTP 6 số (KHÔNG lưu mã gốc)';
COMMENT ON COLUMN password_reset_otp.reset_token_hash IS 'sha256 của vé cấp sau khi xác minh OTP — dùng để đặt mật khẩu mới';

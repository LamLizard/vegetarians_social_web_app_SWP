-- Manual, operator-reviewed artifact. Run before deploying the post edit request code.
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS public.post_edit_requests (
  post_edit_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id BIGINT NOT NULL UNIQUE REFERENCES public.post(post_id) ON DELETE CASCADE,
  account_id BIGINT NOT NULL REFERENCES public.account(account_id),
  request_id UUID NOT NULL,
  request_fingerprint CHARACTER(64) NOT NULL,
  base_updated_at TIMESTAMPTZ NOT NULL,
  post_type post_type_enum NOT NULL,
  title VARCHAR(255) NOT NULL,
  content TEXT NOT NULL,
  thumbnail_url TEXT,
  youtube_url TEXT,
  category_ids BIGINT[] NOT NULL,
  moderation_receipt JSONB NOT NULL,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.post_edit_request_receipts (
  account_id BIGINT NOT NULL REFERENCES public.account(account_id),
  request_id UUID NOT NULL,
  request_fingerprint CHARACTER(64) NOT NULL,
  post_edit_request_id BIGINT NOT NULL,
  outcome VARCHAR(16) NOT NULL CHECK (outcome IN ('pending', 'approved', 'rejected', 'cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (account_id, request_id)
);

ALTER TYPE public.notification_type_enum ADD VALUE IF NOT EXISTS 'post_edit_rejected';

COMMIT;
